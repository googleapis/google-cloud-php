namespace Google\Cloud\Dev;

/**
 * Get release notes for a component
 * @internal
 */
class ReleaseNotes
{
    private const VERIFY_MARKER_START = '<!-- RELEASE_VERIFY_START -->';
    private const VERIFY_MARKER_END = '<!-- RELEASE_VERIFY_END -->';

    private string $rawChangelog;

    /**
     * @var array
     */
    private $changelog;

    /**
     * @var array
     */
    private $versions;

    /**
     * @param string $changelog The full release changelog.
     */
    public function __construct($changelog)
    {
        $this->rawChangelog = $changelog;
        $this->parseChangelog($changelog);
    }

    /**
     * Get release notes for a component.
     *
     * @param string $component The component ID
     * @return string|null
     */
    public function get($component)
    {
        return isset($this->changelog[$component])
            ? $this->changelog[$component]
            : null;
    }

    /**
     * Get the version for the component in the release notes
     *
     * @param string $component The component ID
     * @return string|null
     */
    public function getVersion($component)
    {
        return isset($this->versions[$component])
            ? $this->versions[$component]
            : null;
    }

    /**
     * Build and upsert the collapsible release verification Markdown section into the release notes.
     *
     * @param string[] $headers
     * @param array<int, string[]> $componentRows
     * @param array<int, array<string, mixed>> $checkRuns
     */
    public function withVerificationTable(
        array $headers,
        array $componentRows,
        array $checkRuns,
        bool $hasFailures,
        bool $hasPending
    ): string {
        $statusLabel = $hasFailures ? 'FAILED' : ($hasPending ? 'PENDING' : 'VERIFIED');
        $lines = [
            self::VERIFY_MARKER_START,
            sprintf('<details><summary>Release Verification (%s)</summary>', $statusLabel),
            '',
        ];

        if (!empty($checkRuns)) {
            $lines[] = '### Post-Submit Checks';
            $lines[] = '| Check | Status |';
            $lines[] = '| --- | --- |';
            foreach ($checkRuns as $run) {
                $runName = $run['name'] ?? 'Unknown';
                $runUrl = $run['html_url'] ?? '';
                $label = $runUrl ? sprintf('[%s](%s)', $runName, $runUrl) : $runName;
                if (($run['status'] ?? '') !== 'completed') {
                    $status = 'PENDING';
                } elseif (GitHub::isCheckRunFailed($run)) {
                    $status = 'FAILED';
                } else {
                    $status = 'OK';
                }
                $lines[] = sprintf('| %s | %s |', $label, $status);
            }
            $lines[] = '';
        }

        $lines[] = '### Component Releases';
        $lines[] = '| ' . implode(' | ', $headers) . ' |';
        $lines[] = '| ' . implode(' | ', array_fill(0, count($headers), '---')) . ' |';
        foreach ($componentRows as $row) {
            $lines[] = '| ' . implode(' | ', $row) . ' |';
        }

        $lines[] = '';
        $lines[] = '</details>';
        $lines[] = self::VERIFY_MARKER_END;

        $verifyMarkdown = implode("\n", $lines);
        $pattern = sprintf(
            '/%s.*?%s/s',
            preg_quote(self::VERIFY_MARKER_START, '/'),
            preg_quote(self::VERIFY_MARKER_END, '/')
        );
        if (preg_match($pattern, $this->rawChangelog)) {
            return (string) preg_replace($pattern, $verifyMarkdown, $this->rawChangelog);
        }

        return rtrim($this->rawChangelog) . "\n\n" . $verifyMarkdown;
    }

    /**
     * Parse the release notes generated by release-please into an associative array,
     * where the key is the component ID and the value is the HTML / markdown
     * release notes for the component.
     *
     * @param string $changelog
     * @return void
     */
    private function parseChangelog($changelog)
    {
        $changelog = (string) preg_replace(
            sprintf('/%s.*?%s/s', preg_quote(self::VERIFY_MARKER_START, '/'), preg_quote(self::VERIFY_MARKER_END, '/')),
            '',
            $changelog
        );
        libxml_use_internal_errors(true);
        $d = new \DOMDocument;
        $d->loadHTML($changelog);
        $details = $d->getElementsByTagName("details");

        foreach ($details as $d) {
            $v = new \DOMDocument;
            $v->loadHTML($d->nodeValue);
            $nodeValue = trim($d->nodeValue);
            $lines = explode(PHP_EOL, $nodeValue);
            $firstLine = array_shift($lines);
            preg_match('/\S{0,}\/(\S{1,}): ([0-9\.]+)/', $firstLine, $matches);
            if (count($matches) > 0) {
                $component = $matches[1];
                $this->changelog[$component] = implode(PHP_EOL, $lines) ?: '### Miscellaneous Chores';
                $this->versions[$component] = $matches[2];
            }
        }
    }
}
